fun main() {
    // Variabel dideklarasikan tanpa inisialisasi
    val d: Int
    // Variabel diberi nilai kemudian
    d = 3
    // Tipe eksplisit dan langsung diinisialisasi
    val e: String = "hello"

    // Contoh tipe dasar lain
    val umur: Int = 20
    val tinggi: Double = 170.5
    val lulus: Boolean = true
    val huruf: Char = 'A'

    println("d = $d")
    println("e = $e")
    println("umur = $umur, tinggi = $tinggi")
    println("lulus = $lulus, huruf = $huruf")
}